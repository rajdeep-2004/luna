/**
 * Dev-only: turns the brush kanji Luna uses into SVG path data (D-039), so the app never ships the
 * 8.6 MB Yuji Boku font. Re-run after adding a glyph: `node app/scripts/bake-kanji.mjs`.
 * Output: app/src/art/kanjiPaths.ts (committed). Each glyph carries its own square viewBox.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import opentype from 'opentype.js';

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));

/**
 * Rank kanji (progression.md §1), stamps, duel blades, seals. Check new glyphs visually after baking:
 * Yuji Boku's 勝 is a composite that opentype.js reassembles wrongly, so it is left out and set in
 * Dela Gothic One where needed.
 */
const GLYPHS = [...'弟子足軽浪人武士侍旗本剣先生大名将軍', ...'正誤負引今日道刀雷一月見事斬'];

const ttf = require.resolve('@expo-google-fonts/yuji-boku/400Regular/YujiBoku_400Regular.ttf');
const buf = readFileSync(ttf);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

const PAD = 0.06;
const out = {};
for (const ch of new Set(GLYPHS)) {
  const glyph = font.charToGlyph(ch);
  if (!glyph || glyph.index === 0) throw new Error(`Yuji Boku has no glyph for ${ch}`);
  // Keep the font's own coordinates (size 100) and give each glyph a square viewBox around its
  // bounds, instead of rewriting points: rewriting broke glyphs whose commands share point objects.
  const p = glyph.getPath(0, 0, 100);
  const bb = p.getBoundingBox();
  const side = Math.max(bb.x2 - bb.x1, bb.y2 - bb.y1) * (1 + PAD * 2);
  const cx = (bb.x1 + bb.x2) / 2;
  const cy = (bb.y1 + bb.y2) / 2;
  const r = (n) => Math.round(n * 10) / 10;
  out[ch] = {
    d: p.toPathData(1),
    box: `${r(cx - side / 2)} ${r(cy - side / 2)} ${r(side)} ${r(side)}`,
  };
}

const body = Object.entries(out)
  .map(([ch, g]) => `  '${ch}': { d: '${g.d}', box: '${g.box}' },`)
  .join('\n');
const file = `/**
 * GENERATED by app/scripts/bake-kanji.mjs from Yuji Boku (SIL OFL 1.1). Do not edit by hand.
 * Brush kanji as SVG path data, each with a square viewBox around the glyph, so the brush font
 * never ships (D-039).
 */
export const KANJI = {
${body}
} as const;

export type KanjiGlyph = keyof typeof KANJI;
`;
const target = path.join(here, '../src/art/kanjiPaths.ts');
writeFileSync(target, file);
console.log(
  `wrote ${Object.keys(out).length} glyphs, ${file.length} bytes → ${path.relative(process.cwd(), target)}`,
);
