/**
 * Dev-only: turns the brush kanji Luna uses into SVG path data (D-039), so the app never ships the
 * 8.6 MB Yuji Boku font. Re-run after adding a glyph: `node app/scripts/bake-kanji.mjs`.
 * Output: app/src/art/kanji.ts (committed). Each glyph is centred in a 100 × 100 box.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import opentype from 'opentype.js';

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));

/** Rank kanji (progression.md §1), stamps, duel blades, seals. */
const GLYPHS = [...'弟子足軽浪人武士侍旗本剣先生大名将軍', ...'正誤勝負引今日道刀雷一月'];

const ttf = require.resolve('@expo-google-fonts/yuji-boku/400Regular/YujiBoku_400Regular.ttf');
const buf = readFileSync(ttf);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

const BOX = 100;
const PAD = 6;
const out = {};
for (const ch of new Set(GLYPHS)) {
  const glyph = font.charToGlyph(ch);
  if (!glyph || glyph.index === 0) throw new Error(`Yuji Boku has no glyph for ${ch}`);
  const raw = glyph.getPath(0, 0, 100);
  const bb = raw.getBoundingBox();
  const w = bb.x2 - bb.x1;
  const h = bb.y2 - bb.y1;
  const scale = (BOX - PAD * 2) / Math.max(w, h);
  const dx = (BOX - w * scale) / 2 - bb.x1 * scale;
  const dy = (BOX - h * scale) / 2 - bb.y1 * scale;
  const p = glyph.getPath(0, 0, 100);
  for (const c of p.commands) {
    for (const [kx, ky] of [
      ['x', 'y'],
      ['x1', 'y1'],
      ['x2', 'y2'],
    ]) {
      if (c[kx] !== undefined) c[kx] = c[kx] * scale + dx;
      if (c[ky] !== undefined) c[ky] = c[ky] * scale + dy;
    }
  }
  out[ch] = p.toPathData(1);
}

const body = Object.entries(out)
  .map(([ch, d]) => `  '${ch}': '${d}',`)
  .join('\n');
const file = `/**
 * GENERATED by app/scripts/bake-kanji.mjs from Yuji Boku (SIL OFL 1.1). Do not edit by hand.
 * Brush kanji as SVG path data in a 100 × 100 box, so the brush font never ships (D-039).
 */
export const KANJI = {
${body}
} as const;

export type KanjiGlyph = keyof typeof KANJI;
export const KANJI_VIEWBOX = '0 0 100 100';
`;
const target = path.join(here, '../src/art/kanji.ts');
writeFileSync(target, file);
console.log(
  `wrote ${Object.keys(out).length} glyphs, ${file.length} bytes → ${path.relative(process.cwd(), target)}`,
);
